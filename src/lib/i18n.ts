export type CurrencyCode =
  | "USD" | "INR" | "CAD" | "AUD" | "EUR" | "GBP" | "JPY" | "BRL" | "SGD" | "CHF" | "SEK";

export type CurrencyDef = {
  code: CurrencyCode;
  symbol: string;
  label: string;
  /** Rate relative to USD (the base every price is stored in). */
  rate: number;
  decimals: number;
  /** true → symbol goes after the amount, e.g. "12,50 kr" */
  suffix?: boolean;
};

