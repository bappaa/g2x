export const getCurrency = (code: string): CurrencyDef =>
  CURRENCIES.find((c) => c.code === code) ?? CURRENCIES[0];

export const isLang = (v: string): v is LangCode =>
  LANGUAGES.some((l) => l.code === v);

export const isCurrency = (v: string): v is CurrencyCode =>
  CURRENCIES.some((c) => c.code === v);

/**
 * Convert a USD-denominated amount and format it in the chosen currency.
 * Rates are seeded above and overridable from Admin → System Settings.
 */
export function formatMoney(
  usd: number | null | undefined,
  cur: CurrencyDef,
  rateOverride?: number
): string {
  const rate = rateOverride ?? cur.rate;
  const n = Number(usd ?? 0) * rate;
  const body = n.toLocaleString("en-US", {
    minimumFractionDigits: cur.decimals,
    maximumFractionDigits: cur.decimals,
  });
  return cur.suffix ? `${body} ${cur.symbol}` : `${cur.symbol}${body}`;
}

