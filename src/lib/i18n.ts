/** Returns a translator that falls back to English, then to the key itself. */
export function translator(lang: LangCode) {
  const pack = packs[lang] ?? en;
  /** `t(key, fallback?)` — chosen language, then English, then the fallback. */
  return (key: string, fallback?: string): string =>
    pack[key] ?? en[key] ?? fallback ?? key;
}

export const dictFor = (lang: LangCode): Dict => ({ ...en, ...(packs[lang] ?? {}) });
