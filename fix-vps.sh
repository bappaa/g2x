const fs = require("fs");
for (const p of ["scripts/seed-sellflow.mts","scripts/reseed-catalog.mts","scripts/seed-delivery-times.mts"]) {
  if (!fs.existsSync(p)) continue;
  let s = fs.readFileSync(p, "utf8");
  const hasImport = s.includes("schema-patches.mjs");
  const hasCall = /await applyPatches\(/.test(s);
  if (hasImport && hasCall) { console.log("    " + p + " already ok"); continue; }
  // Strip any half-applied state before re-patching.
  s = s.replace(/import \{ applyPatches \} from "\.\.\/src\/lib\/schema-patches\.mjs";\n/g, "");
  s = s.replace(/[ \t]*\/\/ Self-heal[^\n]*\n[ \t]*await applyPatches\(db\);\n/g, "");
  s = s.replace(
    /import \{ makeDb(, resolveDbConfig)? \} from ".\/db-url.mjs";/,
    (m) => m + "\nimport { applyPatches } from \"../src/lib/schema-patches.mjs\";"
  );
  s = s.replace(/async function main\(\)[^{]*\{\n/,
    (m) => m + "  // Self-heal the schema so command order cannot break this.\n  await applyPatches(db);\n");
  fs.writeFileSync(p, s);
  console.log("    " + p + " patched");
}
'

