const fs = require("fs");
const p = "scripts/deploy-migrate.mts";
let s = fs.readFileSync(p, "utf8");
if (!s.includes("schema-patches.mjs")) {
  // Drop the old regex-based extractor and import the shared list instead.
  const i = s.indexOf("/** Pull the SQL statements out of");
  const j = s.indexOf("const benign =");
  if (i > -1 && j > i) s = s.slice(0, i) + s.slice(j);
  s = s.replace(/const benign = .*\n\n?/, "");
  s = s.replace("const list = patches();", "const list = PATCHES;");
  s = s.replace("if (benign(msg)) present++;", "if (isBenignSchemaError(msg)) present++;");
  s = s.replace(
    /import \{ readFileSync(, [^}]*)? \} from "node:fs";/,
    (m) => m.replace("readFileSync, ", "").replace("readFileSync", "existsSync, mkdirSync")
  );
  if (!s.includes("existsSync")) {
    s = s.replace(/^import /m, "import { existsSync, mkdirSync } from \"node:fs\";\nimport ");
  }
  s = s.replace(
    "import { resolveDbConfig } from \"./db-url.mjs\";",
    "import { resolveDbConfig } from \"./db-url.mjs\";\nimport { PATCHES, isBenignSchemaError } from \"../src/lib/schema-patches.mjs\";"
  );
  fs.writeFileSync(p, s);
  console.log("    deploy-migrate patched");
} else {
  console.log("    already patched");
}
'

